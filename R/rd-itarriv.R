#' The Correlates of International Tourism Arrivals
#'
#' A data set on the correlates of international tourism arrivals, from around 2019.
#'
#' @format A data frame with 149 observations on the following 8 variables.
#' \describe{
#' \item{\code{country}}{a character vector for the English country name}
#' \item{\code{iso3c}}{a character vector for the three-character ISO code}
#' \item{\code{ln_itarriv}}{international tourism, number of arrivals (log-transformed)}
#' \item{\code{ln_airtranspc}}{air transport, passengers carried (log-transformed)}
#' \item{\code{relprice}}{the price-level ratio of the PPP conversion factor (GDP) to the market exchange rate}
#' \item{\code{ln_gdppc}}{GDP per capita in constant 2015 USD (log-transformed)}
#' \item{\code{pvest}}{political stability and absence of violence/terrorism (estimate)}
#' \item{\code{fcas}}{a dummy variable indicating whether the state is a "Fragile and conflict affected situation"}
#' }
#'
#' @details
#'
#' Data generated by use of the \pkg{WDI} package on 25 September 2025. Underlying
#' sources are multiple. In total, these are the UN World Tourism Organization
#' (tourism arrivals), the International Civil Aviation Organization (air transport),
#' World Development Indicators (relative price), and Worldwide Governance
#' Indicators (political stability). GDP per capita data draw from various sources
#' too indirectly specified by the World Bank Group to say here. The dummy
#' variable for fragile and conflict-affected situations come from the \code{wb_groups}
#' data frame in this package and are current as of the 2025 fiscal year.
#'
#' Tourism arrivals are for the 2019 fiscal year. Relative price, GDP per capita,
#' political violence, and air transport passengers carry forward whatever is the
#' most current observation from 2014 as the oldest year. The most recent
#' observation possible for these indicators is 2018. I teach students how to do
#' this on my blog.
#'
#' Relative price is theoretically unbounded at the right, but bound at the left
#' at 0. It will never be observed, but 0 represents a conceptual extreme in which
#' a country is infinitely cheaper than the United States. 1 is the United States.
#' Higher values than 1 indicate a country's currency is relatively more expensive
#' compared to the U.S. dollar.
#'
#' Mali apparently had 0 air transport passengers in the most recent year
#' available, per the procedures I used here. I excluded Mali from this analysis
#' to avoid the discomfort of the undefined log of 0 and the discomfort of having
#' to be super technical with what a logarithmic transformation of `x + 1` is
#' actually communicating. See Chen and Roth (2024) on this point.
#'
#' Some of these indicators are no longer supported by the World Bank's API. Use
#' only for the intended purpose of doing teaching students about the simple
#' linear model with an application that might make H. Peter Gray proud if
#' he were still with us.
#'
#' @references
#'
#' Chen, Jiafeng, and Jonathan Roth. 2024. "Logs with Zeros? Some Problems and
#' Solutions." \emph{The Quarterly Journal of Economics} 139(2): 891--936.
#'
#' Miller, Steven V. 2024. "Make Simple Cross-Sectional Data with World Bank
#' Data (from `{WDI}`). URL: \url{https://svmiller.com/blog/2024/10/make-simple-cross-sectional-world-bank-data-wdi/}
#'
